'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'css/style.css'), 'utf8');
const offline = fs.readFileSync(path.join(root, 'js/offline.js'), 'utf8');
const catalog = JSON.parse(fs.readFileSync(path.join(root,'catalogo.json'),'utf8'));
const available = catalog.tracks.filter(t=>t.src && Number(t.duration)>0);
assert.equal(available.length,catalog.tracks.length,'Todas as faixas devem estar disponíveis para download');
assert.match(html,/id="downloads-dashboard"/,'Painel de downloads deve aparecer em Explorar');
assert.match(html,/id="offline-available-tracks"/,'Lista de músicas para baixar ausente');
assert.match(html,/id="offline-tracks"/,'Lista de downloads salvos ausente');
assert.match(html,/data-action="open-downloads"/,'Atalho da página inicial ausente');
assert.match(js,/case 'open-downloads': jumpToDownloads/);
assert.match(js,/case 'open-offline-saved': jumpToDownloads/);
assert.match(js,/case 'open-offline-available': jumpToDownloads/);
assert.doesNotMatch(js,/stream-only-badge/,'Não oculte downloads para músicas do catálogo');
assert.match(js,/download-track-button/,'Botão de download legível ausente');
assert.doesNotMatch(js,/t\.downloadAllowed === true/,'Todas as músicas devem exibir o botão Baixar');
assert.match(offline,/isCatalogAudio\(track.src\)/,'Download restrito ao próprio catálogo');
assert.match(html,/id="offline-network-notice"/,'Aviso de falta de internet ausente');
assert.match(js,/window\.addEventListener\('offline', updateConnectionNotice\)/,'Sem aviso de offline');
assert.match(html,/id="preload-status"/,'Indicador de pré-carregamento ausente');
assert.match(js,/addEventListener\('canplay'/,'Pré-carregamento precisa avisar quando pode iniciar');
assert.match(css,/\.download-track-button/);
assert.match(css,/@media\(max-width:740px\)/);
console.log('DOWNLOADS UI OK:',catalog.tracks.length,'músicas com botão Baixar e reprodução offline individual.');
