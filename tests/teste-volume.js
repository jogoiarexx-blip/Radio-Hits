'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'catalogo.json'),'utf8'));
assert.ok(catalog.tracks.length>0);
assert.ok(catalog.tracks.every(t=>Number.isFinite(t.gainDb)&&t.gainDb<=0&&t.gainDb>=-10),'Ganho fora do limite seguro');
assert.ok(catalog.tracks.every(t=>t.loudnessLufs===null||Number.isFinite(t.loudnessLufs)),'Medição inválida');
assert.match(html,/id="leveling-toggle"/);
assert.match(app,/leveling:state\.leveling/);
const java=fs.readFileSync(path.join(root,'android/app/src/main/java/br/com/radiohits/app/MainActivity.java'),'utf8');
assert.match(java,/radiohits_gain_db/);
assert.match(java,/onMediaItemTransition[\s\S]*?applyNativeVolume/);
assert.match(java,/setLeveling\(boolean enabled\)/);
const start=app.indexOf('  function gainFactor('),stop=app.indexOf('  function setPlayVisuals()',start);
assert.ok(start>0&&stop>start);
const state={volume:.8,leveling:true,currentId:'foo'};
const testAudio={volume:0},standby={volume:0};
const tracks={foo:{gainDb:-6},bar:{gainDb:-3},bad:{gainDb:99},very:{gainDb:-99}};
const ctx={state,audio:testAudio,standby,tracks,primedTrackId:'bar',nativeBridge:false,
  trackById:(id)=>tracks[id],console,Math,Number};
vm.createContext(ctx);
vm.runInContext(app.slice(start,stop),ctx);
const run=(s)=>vm.runInContext(s,ctx);
assert.ok(Math.abs(run('gainFactor(tracks.foo)')-Math.pow(10,-6/20))<.0001);
assert.equal(run('gainFactor(tracks.bad)'),1);
assert.ok(Math.abs(run('gainFactor(tracks.very)')-Math.pow(10,-10/20))<.0001);
run('applyVolumeForTrack(tracks.foo)');
assert.ok(Math.abs(testAudio.volume-.8*Math.pow(10,-6/20))<.0001);
assert.ok(Math.abs(standby.volume-.8*Math.pow(10,-3/20))<.0001);
state.leveling=false;
run('applyVolumeForTrack(tracks.foo)');
assert.equal(testAudio.volume,.8);
assert.equal(standby.volume,.8);
state.volume=0;
state.leveling=true;
run('applyVolumeForTrack(tracks.foo)');
assert.equal(testAudio.volume,0);
console.log('VOLUME OK: atenuação, sem boost, mute, standby, toggle e Media3.');

