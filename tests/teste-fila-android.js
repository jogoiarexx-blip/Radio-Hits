'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const get = p => fs.readFileSync(path.join(root,p),'utf8');
const worker = get('android/app/src/main/java/br/com/radiohits/app/DownloadWorker.java');
const store = get('android/app/src/main/java/br/com/radiohits/app/OfflineStore.java');
const activity = get('android/app/src/main/java/br/com/radiohits/app/MainActivity.java');
const build = get('android/app/build.gradle');
const html = get('index.html');
const sw = get('sw.js');
const webOffline = get('js/offline.js');
const app = get('js/app.js');

assert.match(build,/androidx\.work:work-runtime:2\.12\.0/);
assert.match(build,/versionCode 10/);
assert.match(worker,/enqueueUniqueWork/,'WorkManager deve persistir por arquivo');
assert.match(worker,/ExistingWorkPolicy\.REPLACE/,'Reenfileirar substitui a tentativa cancelada');
assert.match(worker,/NetworkType\.CONNECTED/,'Fila deve aguardar rede');
assert.match(worker,/BackoffPolicy\.EXPONENTIAL/);
assert.match(worker,/cancelUniqueWork/);
assert.match(worker,/getWorkInfosByTag/);
assert.match(worker,/synchronized \(OfflineStore\.downloadLock\(url\)\)/);
assert.match(store,/If-Range/);
assert.match(store,/Content-Range/);
assert.match(store,/downloadLock\(url\)/);
assert.match(store,/stop\.canceled\(\)/);
assert.match(store,/size!=expected/);
assert.match(store,/partial\.renameTo\(target\)/);
assert.match(store,/setInstanceFollowRedirects\(false\)/);
assert.match(activity,/case "listDownloadJobs"/);
assert.match(activity,/case "pauseOffline"/);
assert.match(activity,/case "cancelOffline"/);
assert.match(webOffline,/supportsJobs/);
assert.match(app,/case 'download-cancel'/);
assert.match(app,/refreshNativeDownloadJobs/);
assert.match(html,/native-bridge\.js\?v=bridge-2/);
assert.match(sw,/native-bridge\.js\?v=bridge-2/);
assert.match(sw,/radio-hits-shell-v14/);
assert.ok(html.indexOf('js/native-bridge.js') < html.indexOf('js/offline.js'));

const calls = [];
const native = {onmessage:null,postMessage:message => calls.push(JSON.parse(message))};
const ctx = {window:{RadioHitsNative:native},setTimeout(){}};
vm.runInNewContext(get('js/native-bridge.js'),ctx);
const bridge = ctx.window.RadioHitsAndroid;
bridge.pauseOffline('https://jogoiarexx-blip.github.io/Radio-Hits/musicas/teste.mp3');
bridge.cancelOffline('https://jogoiarexx-blip.github.io/Radio-Hits/musicas/teste.mp3');
assert.equal(calls[0].method,'pauseOffline');
assert.equal(calls[1].method,'cancelOffline');
(async() => {
  const pending = bridge.listDownloadJobs();
  assert.equal(calls[2].method,'listDownloadJobs');
  native.onmessage({data:JSON.stringify({id:calls[2].id,value:'[{"state":"queued"}]'})});
  assert.equal(await pending,'[{"state":"queued"}]');
  console.log('FILA ANDROID OK: API de fila, pausa, cancelamento, retomada HTTP e cache versionado.');
})().catch(e=>{console.error(e);process.exitCode=1;});
